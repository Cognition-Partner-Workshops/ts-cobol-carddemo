def ticketDoc(design, t, dd, td) -> str:
    m = design["meta"]
    b = lambda items: "\n".join(f"  - {x}" for x in items)  # noqa: E731
    bb = lambda items: "\n".join(f"    - {x}" for x in items)  # noqa: E731
    fi = {f["id"]: f for f in dd.frozenInterfaces}
    frozen = [f"{i} {fi[i]['what']} ({fi[i]['where']})" if i in fi else i for i in t["frozen"]]
    defines = [f"{i} {fi[i]['what']} - defined by this ticket and frozen once it is merged" for i in t["defines"]]
    deps = [f"ticket {d:02d} ({next(x for x in td.tickets if x['n'] == d)['slug']}) merged" for d in t["deps"]] or ["none"]
    excludedAlways = [f"{x}" for x in td.common]
    return f"""# {t['id']} - {t['title']}

{generatedNote}

- **Work item:** {t['workItem']} - {t['outcome']}
- **Source:** `{m['repository']}`, baseline `{m['baseline']['sha']}`, stream root {m['root']} (`app/jcl/INTCALC.jcl` -> `app/cbl/CBACT04C.cbl`). Branch from `{m['designBranch']}` or its successor.
- **Context:**
  - Rules: {", ".join(t['rules']) or "none"} (`modernization/rules/interest/rules.yaml`)
  - Architecture: `modernization/design/architecture.md` version {m['architectureVersion']}. {t['context']}
  - Data-map rows (`modernization/design/data-map-interest.md`): {t['dataRows']}
  - Decisions: {t['decisions']}
- **Scope:**
  - Allowed files:
{bb(t['allowed'])}
  - Frozen shared interfaces:
{bb(frozen + defines)}
  - Excluded work:
{bb(t['excluded'])}
- **Dependencies:**
{b(deps)}
- **Acceptance:**
{b(t['acceptance'])}
- **Verification:**
{b(t['verification'])}
- **Deliverables:** one branch and one pull request; the test output named under Verification, pasted or attached to the pull request; a list of gaps - {t['gaps']}.
- **Ticket writes:** prohibited
- **Restrictions:** no edits to `app/` or `fixtures/*/expected`; no merge or deploy. Also untouched: {"; ".join(excludedAlways[2:])}.
"""


def ticketsReadme(design, tickets, td) -> str:
    c = design["counts"]
    by = defaultdict(list)
    for t in tickets:
        by[t["group"]].append(t)
    link = lambda t: f"[{t['id']}-{t['slug']}]({t['id']}-{t['slug']}.md)"  # noqa: E731
    out = [head(design, "Ticket queue - interest stream")]
    out.append(f"""
{c['tickets']} bounded engineering tickets. Each follows the same contract (work item, source, context, scope,
dependencies, acceptance, verification, deliverables, ticket writes, restrictions). Business and release decisions are
not tickets: they are in `modernization/rules/interest/decisions.md` and [../decisions-release.md](../decisions-release.md).
An open QUIRK is built as the legacy behaviour and cited by id.

No ticket has been created in any external system and no implementation session has been started.

## The pilot

**Ticket {link(by['pilot'][0])} is the pilot.** It is a thin end-to-end slice with no dependencies: read the input
files of one case, compute interest on the simplest path, write the outputs. Its result can already be compared with
the estate's comparator on the fixture case `i01-baseline`. It also fixes the ports (FI-3) and the parity entry point
(FI-6) the later tickets build on.

## Dependency order

```mermaid
flowchart LR
  T01[01 pilot] --> T03[03 codec]
  T01 --> T04[04 rules]
  T02[02 schema] --> T05[05 loader]
  T03 --> T05
  T02 --> T06[06 calc step]
  T04 --> T06
  T02 --> T07[07 export]
  T03 --> T07
  T06 --> T08[08 error paths]
  T05 --> T09[09 parity gate]
  T06 --> T09
  T07 --> T09
  T08 --> T09
  T05 --> T10[10 data-move kit]
  T07 --> T10
```

""")
    out.append(table(["Ticket", "Title", "Starts after", "Group"],
                     [[link(t), t["title"], ", ".join(f"{d:02d}" for d in t["deps"]) or "nothing", td.groups[t["group"]]] for t in tickets]))
    ids = lambda g: ", ".join(t["id"] for t in by[g])  # noqa: E731
    out.append(f"""

* **Can start in parallel, at once:** {ids('pilot')} (pilot) and {ids('schema')} (schema). Neither depends on anything.
* **Can start in parallel once the pilot is merged:** {ids('after-pilot')}. They do not wait on the schema.
* **Wait on the schema (ticket 02):** {ids('waits-schema')}. Of these, 05 and 07 also need the codec (03), 06 also needs the rules (04), and 08 needs 06.
* **Final gates:** {ids('gate')}. Ticket 09 closes only when all seven fixture cases pass through the database in CI; ticket 10 closes when the reconciliation and side-by-side reports can be produced. Neither changes product code; a defect found at a gate goes back to the ticket that owns the code.

## Shared rules of every ticket

* Frozen interfaces are listed in `architecture.md`, section 9. A ticket that needs one changed stops and reports it as a gap.
* No edits to `app/` or `fixtures/*/expected`; no merge or deploy; one branch and one pull request per ticket.
* A ticket does not write to tickets (its own or others); what it could not do goes into the pull request as a gap.
""")
    return "".join(out)


def render(design, tickets, dd, td, manifest) -> dict[str, str]:
    out = {"architecture.md": architecture(design, dd, manifest), "data-map-interest.md": dataMapDoc(design, dd),
           "decisions-release.md": releaseDoc(design, dd), "strategy-interest.md": strategy(design, dd),
           "tickets/README.md": ticketsReadme(design, tickets, td)}
    for t in tickets:
        out[t["file"]] = ticketDoc(design, t, dd, td)
    # placeholders such as <case> would be read as HTML tags by a Markdown renderer
    return {name: re.sub(r"<(case|DSN|chain|slug)>", r"&lt;\1&gt;", text) for name, text in out.items()}
