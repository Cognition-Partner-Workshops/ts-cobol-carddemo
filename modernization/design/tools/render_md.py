def dataMapDoc(design, dd) -> str:
    c = design["counts"]
    out = [head(design, "Data map - interest stream")]
    out.append(f"""
Every field of the five copybooks ({c['fields']} rows: elementary fields, the two group keys and the fillers) mapped to
a column of schema `carddemo`. Row ids are `<copybook>/<field>`; tickets cite them. Offsets start at 0 and lengths are
in bytes, as in the stream manifest.

## Encoding rules

""")
    out.append(table(["Rule", "Applies to", "Reading a record", "Writing a record"], [[e["id"], e["applies"], e["decode"], e["encode"]] for e in design["encodingRules"]]))
    out.append("\n\nIn the fixture files the same bytes appear as ISO-8859-1 characters: `{` and `A`-`I` end a positive amount, `}` and `J`-`R` a negative one "
               "(`0000010000{` is +1000.00 as S9(09)V99).\n")
    byCopybook = defaultdict(list)
    for r in design["dataMap"]:
        byCopybook[r["copybook"]].append(r)
    for t in dd.tables:
        if not t["copybook"]:
            continue
        rows = byCopybook[t["copybook"]]
        length = sum(r["length"] or 0 for r in rows)
        out.append(f"\n## {t['copybook']} -> `{t['name']}`\n\nLegacy dataset `{t['legacy']}`, record length {length}. {t['kind'].capitalize()} table.\n\n")
        out.append(table(["Field", "PIC", "Offset", "Length", "Kind", "Rule", "Column", "Type", "Use by the job", "Note"],
                         [[f"`{r['field']}`", r["pic"], "" if r["offset"] is None else r["offset"], "" if r["length"] is None else r["length"],
                           r["kind"], r["encoding"], f"`{r['column']}`", f"`{r['pgType']}`", r["role"], r["note"]] for r in rows]))
        extra = dd.extraColumns.get(t["id"])
        if extra:
            out.append("\n\nColumns with no copybook field:\n\n" + table(["Column", "Type", "Purpose"], [[f"`{a}`", f"`{b}`", x] for a, b, x in extra]))
        out.append("\n")
    out.append("\n## `carddemo.interest_run` (no copybook)\n\n" + table(["Column", "Type", "Purpose"], [[f"`{a}`", f"`{b}`", x] for a, b, x in dd.extraColumns["interestRun"]]) + "\n")
    out.append("\n## Keys and alternate indexes\n\n")
    out.append(table(["Table", "Legacy key", "Primary key", "Legacy alternate index", "Index"],
                     [[f"`{t['name']}`", t["legacyKey"], f"`{t['primaryKey']}`", t["legacyIndexes"], "; ".join(t["indexes"]) or "-"] for t in dd.tables if t["kind"] != "framework"]))
    out.append("\n\nNo foreign key is declared between the replica tables: the legacy files have none, and a balance whose account or rate is "
               "missing must reach the job so that it stops as CBACT04C does (INT-R08).\n")
    out.append(f"\n## Mapping gaps that could not be closed ({c['gaps']})\n\n")
    out.append(table(["Gap", "What is not known", "Detail", "Affects", "Who can close it", "What closes it"],
                     [[g["id"], g["title"], g["detail"], g["affects"], g["owner"], g["closes"]] for g in design["gaps"]]))
    out.append("\n")
    return "".join(out)


